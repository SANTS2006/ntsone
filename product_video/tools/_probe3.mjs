import { chromium } from "playwright-core";
const browser = await chromium.launch({ channel: "chrome", headless: true, args: ["--disable-gpu", "--disable-dev-shm-usage"] });
const c1 = await browser.newContext({ viewport: { width: 1920, height: 1080 }, colorScheme: "light" });
const p1 = await c1.newPage();
await p1.goto("http://localhost:5188/login", { waitUntil: "domcontentloaded" });
await p1.fill('input[type="email"]', "bootcamp.admin@example.com");
await p1.fill('input[type="password"]', "ProgramAdmin123!");
await p1.click('button[type="submit"]');
await p1.waitForURL("**/admin**");
const state = await c1.storageState();
console.log("cookies", state.cookies.map((c) => c.name + ":" + c.path).join(", "));
await c1.close();
const c2 = await browser.newContext({ viewport: { width: 1920, height: 1080 }, colorScheme: "light", deviceScaleFactor: 1, storageState: state });
const p2 = await c2.newPage();
await p2.addInitScript(() => localStorage.setItem("ntsone-theme", "light"));
p2.on("crash", () => console.log("CRASH"));
await p2.goto("http://localhost:5188/admin", { waitUntil: "domcontentloaded" });
const t0=Date.now(); let n=0; while(Date.now()-t0<4000){ await p2.screenshot({type:"jpeg",quality:85,animations:"allow"}); n++; await new Promise(r=>setTimeout(r,40)); } console.log("shots",n);
console.log("title", await p2.title(), p2.url());
await p2.screenshot({ path: "_probe2.png" });
await browser.close();
